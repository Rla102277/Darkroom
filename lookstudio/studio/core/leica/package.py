from __future__ import annotations

import hashlib
import io
import json
import re
import zipfile

from core.leica.authoritative import read_authoritative_member


def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "leica_look"


def generated_injector_source() -> bytes:
    source = read_authoritative_member("uploader.py").decode("utf-8")
    source = source.replace(
        "if len(out)!=MAX_DOWNLOADABLE_LOOKS:\n        raise SystemExit(f\"expected {MAX_DOWNLOADABLE_LOOKS} Looks, got {len(out)}\")",
        "if not out or len(out)>MAX_DOWNLOADABLE_LOOKS:\n        raise SystemExit(f\"expected 1..{MAX_DOWNLOADABLE_LOOKS} Looks, got {len(out)}\")",
    )
    source = source.replace(
        'print("AUTO-INSTALL: 9-Look final Infinite Arch set.")',
        'print(f"AUTO-INSTALL: generated {len(manifest)}-Look package.")',
    )
    source = source.replace('assets=validate(root,manifest)',
                            'assets=validate(root,manifest); manifest=[L for L,_,_ in assets]')
    source = source.replace("final IA Looks", "package Looks").replace("final nine", "complete package")
    return source.encode("utf-8")


def package_readme(name: str, look_id: int, base_name: str, provenance: str, payload_sha256: str) -> bytes:
    return f"""# {name}

Generated by Film Look Studio.

## Look

- ID: {look_id}
- Leica base: {base_name}
- Payload SHA-256: `{payload_sha256}`
- Source provenance: {provenance}

## Prepare on iPhone

Download and extract this entire ZIP in the iPhone Files app. Open
`injector.py` from the extracted folder in an iPhone Python interpreter.
The injector embeds its manifest, CUBE and icon with checksum validation.
It can run by itself; keep the rest of the package as an editable source record.

If the interpreter provides a terminal, you can validate without connecting:
`python injector.py --list`.

## Install from iPhone

The Replit web application never connects to a camera. `injector.py` is the
v1.2 proven FOTOS-assisted uploader adapted only to accept a generated package
containing 1–9 Looks, with assets embedded for standalone use. No computer is used in the installation workflow.

1. On the iPhone, open Leica FOTOS and connect to the camera normally.
2. Wait until FOTOS confirms that the camera is connected.
3. Without disconnecting or changing the camera network, use the iPhone app
   switcher to return to the Python interpreter.
4. Open `injector.py` and tap the interpreter's Run or Play button. If the
   interpreter uses a terminal, run `python injector.py`.
5. The script validates every asset, reads the current Look table, performs a
   single-attempt write, re-reads the table, and reports verification.

Do not rerun after an ambiguous network failure until the camera state has been
inspected. Existing downloadable Looks can consume the camera's nine slots.
""".encode()


