def build_look_package(
    *,
    name: str,
    look_id: int,
    base: int,
    icon: bytes,
    cube: bytes,
    payload: bytes,
    provenance: str,
    description: str,
    graph: dict | None = None,
    source_components: list[dict] | None = None,
) -> bytes:
    slug = slugify(name)
    base_name = "Monochrome" if base == 1 else "Standard"
    manifest_record = {
        "key": slug,
        "name": name,
        "id": look_id,
        "base": base,
        "base_name": base_name,
        "mono": base == 1,
        "enabled": True,
        "cube_sha256": hashlib.sha256(cube).hexdigest(),
        "icon_sha256": hashlib.sha256(icon).hexdigest(),
        "cube": f"looks/{slug}/look.CUBE",
        "cube_bytes": len(cube),
        "icon": f"looks/{slug}/look.bmp",
        "icon_bytes": len(icon),
        "payload_sha256": hashlib.sha256(payload).hexdigest(),
        "payload": f"looks/{slug}/look.leica-payload.bin",
        "compiler": "Film Look Studio compiler v1",
        "round_trip_verified": True,
        "source_provenance": provenance,
    }
    files = {
        "injector.py": self_contained_injector([manifest_record], {manifest_record["cube"]: cube, manifest_record["icon"]: icon}),
        "looks_manifest.json": json.dumps([manifest_record], indent=2, sort_keys=True).encode(),
        f"looks/{slug}/look.CUBE": cube,
        f"looks/{slug}/look.bmp": icon,
        f"looks/{slug}/look.leica-payload.bin": payload,
        "README.md": package_readme(name, look_id, base_name, provenance, manifest_record["payload_sha256"]),
        "CHEAT_SHEET.md": cheat_sheet(name, look_id, base_name, description, provenance),
        "sources/provenance.json": json.dumps({"description": description, "provenance": provenance, "components": source_components or []}, indent=2).encode(),
    }
    if graph is not None:
        files["look-graph.json"] = json.dumps(graph, indent=2, sort_keys=True).encode()
    checksums = "\n".join(f"{hashlib.sha256(data).hexdigest()}  {path}" for path, data in sorted(files.items())) + "\n"
    files["checksums.txt"] = checksums.encode()
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w") as archive:
        for path, data in sorted(files.items()):
            info = zipfile.ZipInfo(path, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, data)
    return output.getvalue()

def self_contained_injector(manifest: list[dict], assets: dict[str, bytes]) -> bytes:
    """Embed validated assets without changing the reference transport functions."""
    import base64
    source = generated_injector_source().decode()
    replacements = {
        'cube=(root/L["cube"]).read_bytes(); icon=(root/L["icon"]).read_bytes()':
        'cube=base64.b64decode(ASSETS[L["cube"]], validate=True); icon=base64.b64decode(ASSETS[L["icon"]], validate=True)',
        'manifest=json.loads((root/"looks_manifest.json").read_text())': 'manifest=EMBEDDED_MANIFEST',
    }
    for old, new in replacements.items():
        if source.count(old) != 1:
            raise RuntimeError("Authoritative injector template changed; review adapter before export")
        source = source.replace(old, new)
    # Literal Python data, never interpolation into executable expressions.
    embedded = '\nimport base64\nEMBEDDED_MANIFEST = ' + repr(manifest)
    embedded += '\nASSETS = ' + repr({path: base64.b64encode(data).decode('ascii') for path, data in assets.items()}) + '\n'
    anchor = 'HOST="192.168.54.1"'
    if source.count(anchor) != 1:
        raise RuntimeError("Authoritative injector anchor changed")
    return source.replace(anchor, embedded + '\n' + anchor).encode()


def combine_look_packages(packages: list[bytes]) -> bytes:
    """Produce one installable pack, not nested installers that reject each other."""
    if not 1 <= len(packages) <= 9:
        raise ValueError("Select between one and nine Looks")
    manifest, files, assets = [], {}, {}
    ids, names, paths = set(), set(), set()
    for index, package in enumerate(packages, 1):
        with zipfile.ZipFile(io.BytesIO(package)) as archive:
            records = json.loads(archive.read("looks_manifest.json"))
            if len(records) != 1:
                raise ValueError("Expected one Look per source package")
            record = records[0]
            if record['id'] in ids:
                raise ValueError(f"Duplicate Leica Look ID {record['id']}; assign distinct Look IDs before building a pack")
            if record['name'] in names:
                raise ValueError("Each Look in a pack must have a distinct name")
            ids.add(record['id']); names.add(record['name']); manifest.append(record)
            for key in ('cube', 'icon', 'payload'):
                path = record[key]
                if path in paths:
                    raise ValueError("Look names resolve to the same package path; rename one Look")
                paths.add(path); files[path] = archive.read(path)
                if key != 'payload':
                    assets[path] = files[path]
            for name in ('README.md', 'CHEAT_SHEET.md', 'sources/provenance.json', 'look-graph.json'):
                if name in archive.namelist():
                    files[f'documentation/{index:02d}/{name}'] = archive.read(name)
    files['looks_manifest.json'] = json.dumps(manifest, indent=2, sort_keys=True).encode()
    files['injector.py'] = self_contained_injector(manifest, assets)
    files['README.md'] = ("# Leica Look pack\n\nRun the single self-contained injector.py on your iPhone to install all selected Looks.\n"
                          "Connect in Leica FOTOS, switch to your Python interpreter while remaining connected, and tap Run.\n"
                          "Validate offline with `python injector.py --list`.\n\n"
                          "Each Look's editable graph, provenance and cheat sheet are under documentation/.\n"
                          "Existing non-matching downloadable Looks must be removed in FOTOS before installation.\n").encode()
    files['checksums.txt'] = ''.join(f'{hashlib.sha256(data).hexdigest()}  {path}\n' for path, data in sorted(files.items())).encode()
    output = io.BytesIO()
    with zipfile.ZipFile(output, 'w') as archive:
        for path, data in sorted(files.items()):
            info = zipfile.ZipInfo(path, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, data)
    return output.getvalue()
